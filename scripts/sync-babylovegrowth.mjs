async function collectGeneratedArticles(currentArticles) {
  const bySlug = new Map(currentArticles.map((article) => [article.slug, article]));
  const entries = await readdir(RESOURCE_ROOT, { withFileTypes: true });

  for (const entry of entries) {
    if (!entry.isDirectory() || bySlug.has(entry.name)) continue;
    const filePath = path.join(RESOURCE_ROOT, entry.name, "index.html");
    if (!existsSync(filePath)) continue;

    const html = await readFile(filePath, "utf8");
    const id = html.match(/babylovegrowth:article-id=([^\s>]+)\s*-->/)?.[1];
    if (!id) continue;

    let articleSchema;
    for (const match of html.matchAll(
      /<script[^>]+type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi
    )) {
      try {
        const parsed = JSON.parse(match[1]);
        const graph = Array.isArray(parsed?.["@graph"]) ? parsed["@graph"] : [parsed];
        articleSchema = graph.find((item) => item?.["@type"] === "Article");
        if (articleSchema) break;
      } catch {
        // Ignore unrelated or malformed structured-data blocks and use HTML fallbacks below.
      }
    }

    const title =
      articleSchema?.headline ||
      stripTags(html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i)?.[1] || entry.name);
    const description =
      articleSchema?.description ||
      html.match(/<meta[^>]+name=["']description["'][^>]+content=["']([^"']*)/i)?.[1] ||
      "";
    const date = formatDate(
      articleSchema?.dateModified ||
        articleSchema?.datePublished ||
        html.match(/Updated\s+(\d{4}-\d{2}-\d{2})/i)?.[1]
    );

    bySlug.set(entry.name, { id, title, slug: entry.name, description, date });
  }

  return [...bySlug.values()].sort(
    (a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title)
  );
}

async function apiGet(pathname) {
  for (let attempt = 0; attempt < MAX_API_ATTEMPTS; attempt += 1) {
    const response = await fetch(`${API_BASE}${pathname}`, {
      headers: {
        "X-API-Key": apiKey,
        "Content-Type": "application/json",
      },
    });

    if (response.ok) return response.json();

    if (response.status === 429 && attempt < MAX_API_ATTEMPTS - 1) {
      const delay = retryDelay(response, attempt);
      console.warn(`BabyLoveGrowth API rate limited ${pathname}; retrying in ${delay}ms.`);
      await sleep(delay);
      continue;
    }

    throw new Error(`BabyLoveGrowth API ${response.status} for ${pathname}`);
  }

  throw new Error(`BabyLoveGrowth API retry limit exceeded for ${pathname}`);
}

async function fetchArticles() {
  const summaries = await apiGet(`/v1/articles?limit=${limit}&offset=0`);
  const articles = [];
  for (const summary of summaries) {
    if (articles.length > 0) await sleep(DETAIL_DELAY_MS);
    articles.push(await apiGet(`/v1/articles/${summary.id}`));
  }
  return articles;
}

async function upsertGeneratedBlock(filePath, markerPairs, content) {
  const original = await readFile(filePath, "utf8");
  const markers = markerPairs.find(
    ([startMarker, endMarker]) => original.includes(startMarker) && original.includes(endMarker)
  );

  if (!markers) {
    const expected = markerPairs
      .map(([startMarker, endMarker]) => `${startMarker} ... ${endMarker}`)
      .join(" or ");
    throw new Error(`Missing generated block markers in ${filePath}. Expected ${expected}`);
  }

  const [startMarker, endMarker] = markers;
  const next = original.replace(
    new RegExp(`${escapeRegExp(startMarker)}[\\s\\S]*?${escapeRegExp(endMarker)}`),
    `${startMarker}\n${content.trim()}\n${endMarker}`
  );
  if (next !== original && !dryRun) await writeFile(filePath, next);
}

async function main() {
  const template = await readFile(TEMPLATE_PATH, "utf8");
  const templateParts = extractTemplateParts(template);
  const articles = reindexOnly ? [] : await fetchArticles();
  const synced = [];

  for (const article of articles) {
    const slug = slugify(article.slug || article.title || String(article.id));
    const dir = path.join(RESOURCE_ROOT, slug);
    const filePath = path.join(dir, "index.html");
    if (existsSync(filePath)) {
      const existing = await readFile(filePath, "utf8");
      if (!existing.includes(`babylovegrowth:article-id=${article.id}`)) {
        console.warn(`Skipping ${slug}: existing non-BabyLoveGrowth page found.`);
        continue;
      }
    }
    const localHero = await localizeHeroImage(article, slug);
    const page = await buildPage(article, templateParts, localHero);
    if (!dryRun) {
      await mkdir(dir, { recursive: true });
      await writeFile(filePath, page);
    }
    synced.push({
      id: article.id,
      title: article.title,
      slug,
      description: article.meta_description || article.excerpt || "",
      date: formatDate(article.created_at),
    });
  }

  const allGenerated = await collectGeneratedArticles(synced);

  const cards = allGenerated
    .map(
      (article) => `      <article class="resource-card">
        <span class="chip">Mitch Russo</span>
        <h2><a href="/resources/${article.slug}/">${escapeHtml(article.title)}</a></h2>
        <p>${escapeHtml(article.description)}</p>
        <a class="resource-card__link" href="/resources/${article.slug}/">Read article &rarr;</a>
      </article>`
    )
    .join("\n");

  const sitemapUrls = allGenerated
    .map(
      (article) => `  <url>
    <loc>${SITE_URL}/resources/${article.slug}/</loc>
    <lastmod>${article.date}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.5</priority>
  </url>`
    )
    .join("\n");

  const llmsItems = allGenerated
    .map((article) => `- ${article.title}: ${SITE_URL}/resources/${article.slug}/`)
    .join("\n");

  await upsertGeneratedBlock(
    path.join(RESOURCE_ROOT, "index.html"),
    [
      ["<!-- AUTO_RESOURCE_RESOURCES_START -->", "<!-- AUTO_RESOURCE_RESOURCES_END -->"],
      ["<!-- BABYLOVEGROWTH_RESOURCES_START -->", "<!-- BABYLOVEGROWTH_RESOURCES_END -->"],
    ],
    cards
  );
  await upsertGeneratedBlock(
    path.join(ROOT, "sitemap.xml"),
    [
      ["<!-- AUTO_RESOURCE_SITEMAP_START -->", "<!-- AUTO_RESOURCE_SITEMAP_END -->"],
      ["<!-- BABYLOVEGROWTH_SITEMAP_START -->", "<!-- BABYLOVEGROWTH_SITEMAP_END -->"],
    ],
    sitemapUrls
  );
  await upsertGeneratedBlock(
    path.join(ROOT, "llms.txt"),
    [
      ["<!-- AUTO_RESOURCE_LLMS_START -->", "<!-- AUTO_RESOURCE_LLMS_END -->"],
      ["<!-- BABYLOVEGROWTH_LLMS_START -->", "<!-- BABYLOVEGROWTH_LLMS_END -->"],
    ],
    llmsItems
  );
  await saveImageDimensionCache();

  console.log(
    `Synced ${synced.length} BabyLoveGrowth article(s); preserved ${allGenerated.length} generated article(s) in site indexes.`
  );
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
